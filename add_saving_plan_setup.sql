-- SAVING & STP PLAN SETUP (₹10,000 Saving - 15-Week Standard Plan)
-- RUN THIS IN YOUR SUPABASE SQL EDITOR

-- 1. Add Saving & STP tracking columns to public.loans table
ALTER TABLE public.loans
ADD COLUMN IF NOT EXISTS is_saving_plan BOOLEAN DEFAULT FALSE,
ADD COLUMN IF NOT EXISTS stp_amount NUMERIC DEFAULT 0,
ADD COLUMN IF NOT EXISTS saving_per_week NUMERIC DEFAULT 0,
ADD COLUMN IF NOT EXISTS total_saving NUMERIC DEFAULT 0;

-- 2. Add EMI vs Saving breakdown columns to public.collection_schedules table
ALTER TABLE public.collection_schedules
ADD COLUMN IF NOT EXISTS emi_amount NUMERIC DEFAULT 0,
ADD COLUMN IF NOT EXISTS saving_amount NUMERIC DEFAULT 0,
ADD COLUMN IF NOT EXISTS plan_name TEXT;

-- 3. Create public.member_savings ledger table to track STP, weekly savings, and withdrawals
CREATE TABLE IF NOT EXISTS public.member_savings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  loan_id BIGINT REFERENCES public.loans(id) ON DELETE CASCADE,
  member_id BIGINT NULL,
  member_name TEXT NULL,
  center_id BIGINT NULL,
  center_name TEXT NULL,
  schedule_id BIGINT NULL,
  week_number INTEGER NULL,
  transaction_type TEXT NOT NULL CHECK (transaction_type IN ('STP', 'WEEKLY_SAVING', 'WITHDRAWAL')),
  amount NUMERIC NOT NULL DEFAULT 0,
  notes TEXT NULL,
  created_by TEXT NULL,
  created_at TIMESTAMP WITH TIME ZONE NULL DEFAULT NOW(),
  CONSTRAINT member_savings_pkey PRIMARY KEY (id)
) TABLESPACE pg_default;

-- 4. Indexes for fast lookup & duplicate prevention
CREATE INDEX IF NOT EXISTS idx_member_savings_loan_id ON public.member_savings USING btree (loan_id) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS idx_member_savings_member_id ON public.member_savings USING btree (member_id) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS idx_member_savings_center_id ON public.member_savings USING btree (center_id) TABLESPACE pg_default;
CREATE UNIQUE INDEX IF NOT EXISTS idx_member_savings_schedule_unique ON public.member_savings USING btree (schedule_id) TABLESPACE pg_default;

-- 5. Grant permissions so Supabase API / service_role can read & write member_savings
GRANT ALL ON TABLE public.member_savings TO postgres, anon, authenticated, service_role;
GRANT USAGE, SELECT ON SEQUENCE public.member_savings_id_seq TO postgres, anon, authenticated, service_role;
ALTER TABLE public.member_savings DISABLE ROW LEVEL SECURITY;
